dragon::arm::FlagSetter dragon::arm::ARMIGNILLifter::cfAddOverflow(
        ignil::Value result, ignil::Value addend, std::uint64_t addr) const {
  // Unsigned overflow: result wrapped around  <=>  result < addend (unsigned).
  // Same polarity as x86's CF for ADD.
  return [this, result, addend, addr](ignil::Block &out, std::uint32_t &tmp) {
    auto t = newTemp(tmp, 1);
    out.append({ignil::Opcode::ULT, t, {result, addend}, addr});
    out.append({ignil::Opcode::COPY, regCF_, {t}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::cfSubNoBorrow(ignil::Value lhs, ignil::Value rhs,
                                           std::uint64_t addr) const {
  // AArch64: C=1 means NO unsigned borrow occurred  <=>  lhs >= rhs
  // (unsigned). Opposite polarity from x86's CF for SUB (which is ULT).
  return [this, lhs, rhs, addr](ignil::Block &out, std::uint32_t &tmp) {
    auto t = newTemp(tmp, 1);
    out.append({ignil::Opcode::UGE, t, {lhs, rhs}, addr});
    out.append({ignil::Opcode::COPY, regCF_, {t}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::ofAddOverflow(ignil::Value lhs, ignil::Value rhs,
                                           ignil::Value result,
                                           std::uint64_t addr) const {
  // Signed overflow when both inputs have the same sign but the result has
  // the opposite sign.
  return [this, lhs, rhs, result, addr](ignil::Block &out, std::uint32_t &tmp) {
    ignil::Const zero{0, ignil::widthOf(lhs)};
    auto sa = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sa, {lhs, zero}, addr});
    auto sb = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sb, {rhs, zero}, addr});
    auto sr = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sr, {result, zero}, addr});
    auto sameSign = newTemp(tmp, 1);
    out.append({ignil::Opcode::EQ, sameSign, {sa, sb}, addr});
    auto diffSign = newTemp(tmp, 1);
    out.append({ignil::Opcode::NEQ, diffSign, {sr, sa}, addr});
    auto vf = newTemp(tmp, 1);
    out.append({ignil::Opcode::AND, vf, {sameSign, diffSign}, addr});
    out.append({ignil::Opcode::COPY, regVF_, {vf}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::ofSubOverflow(ignil::Value lhs, ignil::Value rhs,
                                           ignil::Value result,
                                           std::uint64_t addr) const {
  // Signed overflow when inputs have different signs and the result sign
  // differs from lhs.
  return [this, lhs, rhs, result, addr](ignil::Block &out, std::uint32_t &tmp) {
    ignil::Const zero{0, ignil::widthOf(lhs)};
    auto sa = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sa, {lhs, zero}, addr});
    auto sb = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sb, {rhs, zero}, addr});
    auto sr = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sr, {result, zero}, addr});
    auto diffAB = newTemp(tmp, 1);
    out.append({ignil::Opcode::NEQ, diffAB, {sa, sb}, addr});
    auto diffRA = newTemp(tmp, 1);
    out.append({ignil::Opcode::NEQ, diffRA, {sr, sa}, addr});
    auto vf = newTemp(tmp, 1);
    out.append({ignil::Opcode::AND, vf, {diffAB, diffRA}, addr});
    out.append({ignil::Opcode::COPY, regVF_, {vf}, addr});
  };
}

std::uint64_t
dragon::arm::ARMIGNILLifter::decodeLogicalImmediate(std::uint64_t encoded,
                                                    unsigned regSize) {
  // Standard ARM ARM "DecodeBitMasks" algorithm for the 13-bit N:immr:imms
  // encoding used by AND/ORR/EOR(S) immediate forms. Not available from any
  // public LLVM header (AArch64_AM lives in LLVM's internal target sources),
  // so reimplemented here. Verified against 6 known encodings obtained via
  // `llvm-mc -show-encoding` (0xff, 0xff00, 0xf0f0f0f0, a 32-bit-high mask,
  // #1, and a 63-bit mask) before being wired in.
  const std::uint64_t imms = encoded & 0x3F;
  const std::uint64_t immr = (encoded >> 6) & 0x3F;
  const std::uint64_t N = (encoded >> 12) & 0x1;

  // Element size comes from the position of the highest set bit of
  // (N:~imms); e.g. N=1 selects the full 64-bit element, N=0 with the top
  // bit of ~imms clear selects a 32-bit element, and so on down to 2 bits.
  const std::uint64_t combined = (N << 6) | (~imms & 0x3F);
  if (combined == 0)
    return 0; // invalid encoding

  const int len = 63 - std::countl_zero(combined);
  const unsigned size = 1u << len;
  const unsigned R = static_cast<unsigned>(immr) & (size - 1);
  const unsigned S = static_cast<unsigned>(imms) & (size - 1);

  // A run of (S+1) set bits (or all of `size` if S is at the max), to be
  // rotated right by R within the `size`-bit element.
  std::uint64_t pattern = (S == size - 1) ? ~std::uint64_t{0}
                                          : ((std::uint64_t{1} << (S + 1)) - 1);
  const std::uint64_t sizeMask =
          (size < 64) ? ((std::uint64_t{1} << size) - 1) : ~std::uint64_t{0};
  pattern &= sizeMask;
  if (R > 0)
    pattern = ((pattern >> R) | (pattern << (size - R))) & sizeMask;

  // Replicate the `size`-bit pattern to fill the full register width.
  std::uint64_t result = pattern;
  for (unsigned w = size; w < regSize; w *= 2)
    result |= result << w;

  if (regSize < 64)
    result &= (std::uint64_t{1} << regSize) - 1;
  return result;
}

dragon::ignil::Value dragon::arm::ARMIGNILLifter::emitShiftedReg(
        const llvm::MCInst &mc, unsigned regOpIdx, unsigned shiftOpIdx,
        ignil::Width width, std::uint64_t addr, ignil::Block &out,
        std::uint32_t &tmp) const {
  auto reg = toReg(mc.getOperand(regOpIdx).getReg());
  ignil::Value base = (!reg || isZeroReg(*reg))
                              ? ignil::Value{ignil::Const{0, width}}
                              : ignil::Value{*reg};

  const auto encoded =
          static_cast<unsigned>(mc.getOperand(shiftOpIdx).getImm());
  const unsigned amount = encoded & 0x3F;
  const unsigned type = (encoded >> 6) & 0x3; // 0=LSL,1=LSR,2=ASR,3=ROR

  if (amount == 0)
    return base; // fast path - covers plain register operands, by far the
                 // most common case (includes the "mov reg,reg" ORR alias).

  auto result = newTemp(tmp, width);
  switch (type) {
    case 0:
      out.append({ignil::Opcode::SHL,
                  result,
                  {base, ignil::Const{amount, 8}},
                  addr});
      break;
    case 1:
      out.append({ignil::Opcode::SHR,
                  result,
                  {base, ignil::Const{amount, 8}},
                  addr});
      break;
    case 2:
      out.append({ignil::Opcode::SAR,
                  result,
                  {base, ignil::Const{amount, 8}},
                  addr});
      break;
    default: {
      // ROR - only valid for logical (AND/ORR/EOR/ANDS) shifted-register
      // forms. IGNIL has no rotate opcode, but a rotate right by `amount`
      // (1..width-1 here; 0 took the fast path) is exactly
      // (x >> amount) | (x << (width - amount)). This used to emit UNDEF.
      auto hi = newTemp(tmp, width);
      out.append({ignil::Opcode::SHR, hi, {base, ignil::Const{amount, 8}},
                  addr});
      auto lo = newTemp(tmp, width);
      out.append({ignil::Opcode::SHL,
                  lo,
                  {base, ignil::Const{width - amount, 8}},
                  addr});
      out.append({ignil::Opcode::OR, result, {hi, lo}, addr});
      break;
    }
  }
  return result;
}

dragon::ignil::Value dragon::arm::ARMIGNILLifter::emitExtendedReg(
        const llvm::MCInst &mc, unsigned regOpIdx, unsigned extOpIdx,
        ignil::Width width, std::uint64_t addr, ignil::Block &out,
        std::uint32_t &tmp) const {
  auto reg = toReg(mc.getOperand(regOpIdx).getReg());
  // Arith-extend immediate: (type << 3) | shift, type 0-3 = UXTB/H/W/X,
  // 4-7 = SXTB/H/W/X.
  const auto imm = static_cast<unsigned>(mc.getOperand(extOpIdx).getImm());
  const unsigned shift = imm & 0x7;
  const unsigned type = (imm >> 3) & 0x7;
  const bool isSigned = type >= 4;
  const ignil::Width fromWidth = 8u << (type & 3); // 8, 16, 32, 64

  ignil::Value v = (!reg || isZeroReg(*reg))
                           ? ignil::Value{ignil::Const{0, width}}
                           : ignil::Value{*reg};
  ignil::Width vWidth = ignil::widthOf(v);
  // Keep the low fromWidth bits, then extend them to the operation width.
  if (fromWidth < vWidth) {
    auto t = newTemp(tmp, fromWidth);
    out.append({ignil::Opcode::TRUNC, t, {v}, addr});
    v = t;
    vWidth = fromWidth;
  }
  if (vWidth < width) {
    auto t = newTemp(tmp, width);
    out.append({isSigned ? ignil::Opcode::SEXT : ignil::Opcode::ZEXT, t, {v},
                addr});
    v = t;
  } else if (vWidth > width) {
    auto t = newTemp(tmp, width);
    out.append({ignil::Opcode::TRUNC, t, {v}, addr});
    v = t;
  }
  if (shift) {
    auto t = newTemp(tmp, width);
    out.append({ignil::Opcode::SHL, t, {v, ignil::Const{shift, 8}}, addr});
    v = t;
  }
  return v;
}

void dragon::arm::ARMIGNILLifter::liftMemForm(const llvm::MCInst &mc,
                                              const MemForm &form,
                                              std::uint64_t addr,
                                              ignil::Block &out,
                                              std::uint32_t &tmp) const {
  // ro: op[0]=Rt, op[1]=Rn, op[2]=Rm, op[3]=signed-extend flag (SXTW/SXTX
  // vs UXTW/LSL), op[4]=shift flag (scale Rm by the access size).
  // Unscaled (LDUR/STUR): op[0]=Rt, op[1]=Rn, op[2]=simm9 in bytes.
  // Base (LDAR/STLR): op[0]=Rt, op[1]=Rn.
  constexpr ignil::Width ptrWidth = 64;
  auto rt = toReg(mc.getOperand(0).getReg());
  auto rn = toReg(mc.getOperand(1).getReg());
  if (!rt || !rn) {
    logger_.log("Error liftMemForm in addr {:#x} bad operands", addr);
    if (rt && !form.isStore)
      emitUndef(*rt, addr, out);
    out.noteUnlifted(addr);
    return;
  }

  ignil::Temp ea = newTemp(tmp, ptrWidth);
  if (form.addrForm == MemForm::Addr::Base) {
    out.append({ignil::Opcode::COPY, ea, {*rn}, addr});
  } else if (form.addrForm == MemForm::Addr::Unscaled) {
    const auto off = static_cast<std::uint64_t>(mc.getOperand(2).getImm());
    out.append({ignil::Opcode::ADD, ea, {*rn, ignil::Const{off, ptrWidth}},
                addr});
  } else {
    auto rm = toReg(mc.getOperand(2).getReg());
    const bool signedExt = mc.getOperand(3).getImm() != 0;
    const bool doShift = mc.getOperand(4).getImm() != 0;
    ignil::Value idx = (!rm || isZeroReg(*rm))
                               ? ignil::Value{ignil::Const{0, ptrWidth}}
                               : ignil::Value{*rm};
    if (ignil::widthOf(idx) < ptrWidth) { // [xn, wm, uxtw|sxtw]
      auto t = newTemp(tmp, ptrWidth);
      out.append({signedExt ? ignil::Opcode::SEXT : ignil::Opcode::ZEXT, t,
                  {idx}, addr});
      idx = t;
    }
    if (doShift) {
      unsigned sh = 0;
      for (ignil::Width b = form.memWidth / 8; b > 1; b >>= 1)
        ++sh;
      if (sh) {
        auto t = newTemp(tmp, ptrWidth);
        out.append({ignil::Opcode::SHL, t, {idx, ignil::Const{sh, 8}}, addr});
        idx = t;
      }
    }
    out.append({ignil::Opcode::ADD, ea, {*rn, idx}, addr});
  }

  if (form.isStore) {
    ignil::Value src = isZeroReg(*rt)
                               ? ignil::Value{ignil::Const{0, form.memWidth}}
                               : ignil::Value{*rt};
    if (ignil::widthOf(src) > form.memWidth) {
      auto t = newTemp(tmp, form.memWidth);
      out.append({ignil::Opcode::TRUNC, t, {src}, addr});
      src = t;
    }
    out.append({ignil::Opcode::STORE, std::nullopt, {ea, src}, addr});
    return;
  }

  ignil::Value loaded = newTemp(tmp, form.memWidth);
  out.append({ignil::Opcode::LOAD, loaded, {ea}, addr});
  if (form.memWidth < rt->width) {
    auto t = newTemp(tmp, rt->width);
    out.append({form.signExtend ? ignil::Opcode::SEXT : ignil::Opcode::ZEXT,
                t, {loaded}, addr});
    loaded = t;
  }
  if (!isZeroReg(*rt))
    writeScalar(*rt, loaded, addr, out, tmp);
}

void dragon::arm::ARMIGNILLifter::writeScalar(const ignil::Reg &reg,
    ignil::Value value, std::uint64_t address, ignil::Block &out, std::uint32_t &tmp) const {
  if (isZeroReg(reg)) return;
  if (reg.offset >= kOffV0 && reg.offset <= kOffV31 &&
      (reg.offset - kOffV0) % 16 == 0 && reg.width < 128) {
    auto wide = newTemp(tmp, 128);
    out.append({ignil::Opcode::ZEXT, wide, {std::move(value)}, address});
    out.append({ignil::Opcode::COPY, ignil::Reg{reg.offset,128,reg.name+"[V]"}, {wide}, address});
  } else out.append({ignil::Opcode::COPY, reg, {std::move(value)}, address});
}

void dragon::arm::ARMIGNILLifter::liftVectorMove(const llvm::MCInst &mc, VectorMove kind,
    std::uint64_t address, ignil::Block &out, std::uint32_t &tmp) const {
  const auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) { out.noteUnlifted(address); return; }
  if (kind == VectorMove::InsertHigh || kind == VectorMove::ExtractHigh) {
    const auto src=toReg(mc.getOperand(1).getReg());
    if (!src) { emitUndef(*dst,address,out); out.noteUnlifted(address); return; }
    if (kind == VectorMove::ExtractHigh) {
      const auto shifted=newTemp(tmp,128),value=newTemp(tmp,64);
      out.append({ignil::Opcode::SHR,shifted,{*src,ignil::Const{64,8}},address});
      out.append({ignil::Opcode::TRUNC,value,{shifted},address});
      writeScalar(*dst,value,address,out,tmp);
    } else {
      const auto wide=newTemp(tmp,128),high=newTemp(tmp,128),low=newTemp(tmp,128),value=newTemp(tmp,128);
      out.append({ignil::Opcode::ZEXT,wide,{isZeroReg(*src) ? ignil::Value{ignil::Const{0,64}} : ignil::Value{*src}},address});
      out.append({ignil::Opcode::SHL,high,{wide,ignil::Const{64,8}},address});
      out.append({ignil::Opcode::AND,low,{*dst,ignil::Const{~0ull,128}},address});
      out.append({ignil::Opcode::OR,value,{low,high},address});
      writeScalar(*dst,value,address,out,tmp);
    }
    return;
  }
  if (kind == VectorMove::Register) {
    const auto src = toReg(mc.getOperand(1).getReg());
    if (!src || src->width != dst->width) {
      emitUndef(*dst, address, out); out.noteUnlifted(address); return;
    }
    writeScalar(*dst, *src, address, out, tmp);
    return;
  }
  const uint64_t immediate = mc.getOperand(1).getImm();
  const unsigned exponentBits = dst->width == 64 ? 11 : 8;
  const unsigned fractionBits = dst->width == 64 ? 52 : 23;
  const uint64_t repeated = ((immediate >> 6) & 1) ? ((1ull << (exponentBits-3))-1) : 0;
  const uint64_t exponent = (((~immediate >> 6) & 1) << (exponentBits-1)) |
                            (repeated << 2) | ((immediate >> 4) & 3);
  const uint64_t bits = ((immediate >> 7) << (dst->width-1)) |
                         (exponent << fractionBits) | ((immediate & 15) << (fractionBits-4));
  writeScalar(*dst, ignil::Const{bits,dst->width}, address, out, tmp);
}

void dragon::arm::ARMIGNILLifter::liftLaneOp(const llvm::MCInst &mc, const LaneOp &op,
    std::uint64_t address, ignil::Block &out, std::uint32_t &tmp) const {
  using O = ignil::Opcode;
  using L = LaneKind;
  auto emit = [&](O code, std::vector<ignil::Value> sources, ignil::Width width) {
    auto result = newTemp(tmp,width);
    out.append({code,result,std::move(sources),address});
    return result;
  };
  auto constant = [](uint64_t value, ignil::Width width) -> ignil::Value { return ignil::Const{value,width}; };
  auto resized = [&](ignil::Value value, ignil::Width width) -> ignil::Value {
    const auto from = ignil::widthOf(value);
    if (from == width) return value;
    return emit(from < width ? O::ZEXT : O::TRUNC,{value},width);
  };
  auto reg = [&](unsigned index) -> ignil::Value {
    auto value = toReg(mc.getOperand(index).getReg());
    if (!value) {
      out.noteUnlifted(address);
      return emit(O::UNDEF,{},op.vector);
    }
    return !isZeroReg(*value) ? ignil::Value{*value} : constant(0,op.lane);
  };
  auto lane = [&](ignil::Value value, unsigned index) -> ignil::Value {
    if (index) value = emit(O::SHR,{value,constant(index*op.lane,8)},ignil::widthOf(value));
    return resized(value,op.lane);
  };
  const auto destination = toReg(mc.getOperand(0).getReg());
  if (!destination) { out.noteUnlifted(address); return; }
  if (op.kind == L::And || op.kind == L::Or || op.kind == L::Xor ||
      op.kind == L::Bic || op.kind == L::Orn || op.kind == L::Not) {
    ignil::Value value = reg(1);
    if (op.kind == L::Not) value = emit(O::NOT,{value},op.vector);
    else {
      auto rhs = reg(2);
      if (op.kind == L::Bic || op.kind == L::Orn) rhs = emit(O::NOT,{rhs},op.vector);
      const auto code = op.kind == L::And || op.kind == L::Bic ? O::AND
                        : op.kind == L::Xor ? O::XOR : O::OR;
      value = emit(code,{value,rhs},op.vector);
    }
    writeScalar(*destination,value,address,out,tmp);
    return;
  }
  if (op.kind == L::Extract) {
    const unsigned index = mc.getOperand(2).getImm();
    writeScalar(*destination,resized(lane(reg(1),index),destination->width),address,out,tmp);
    return;
  }
  if (op.kind == L::InsertGpr || op.kind == L::InsertLane) {
    const unsigned index = mc.getOperand(2).getImm();
    auto value = op.kind == L::InsertGpr ? resized(reg(3),op.lane)
                                        : lane(reg(3),mc.getOperand(4).getImm());
    auto wide = resized(value,128);
    auto mask = resized(constant(maskToWidth(~0ull,op.lane),op.lane),128);
    if (index) {
      wide = emit(O::SHL,{wide,constant(index*op.lane,8)},128);
      mask = emit(O::SHL,{mask,constant(index*op.lane,8)},128);
    }
    auto keep = emit(O::AND,{reg(1),emit(O::NOT,{mask},128)},128);
    writeScalar(*destination,emit(O::OR,{keep,wide},128),address,out,tmp);
    return;
  }
  ignil::Value value = constant(0,op.lane);
  if (op.kind == L::DupGpr) value = resized(reg(1),op.lane);
  else if (op.kind == L::DupLane) value = lane(reg(1),mc.getOperand(2).getImm());
  else {
    uint64_t immediate = mc.getOperand(1).getImm();
    if (op.kind == L::Immediate64) {
      uint64_t expanded = 0;
      for (unsigned byte=0;byte<8;++byte)
        if (immediate & (1ull << byte)) expanded |= 0xffull << (8*byte);
      immediate = expanded;
    }
    if (op.kind == L::Immediate && op.lane > 8) immediate <<= mc.getOperand(2).getImm();
    if (op.kind == L::ImmediateMsl) {
      const unsigned shift = mc.getOperand(2).getImm() & 255;
      immediate = (immediate << shift) | ((1ull << shift)-1);
    }
    if (op.invert) immediate = ~immediate;
    value = constant(maskToWidth(immediate,op.lane),op.lane);
  }
  auto part = resized(value,op.vector);
  ignil::Value result = part;
  for (unsigned index = 1; index < op.vector/op.lane; ++index) {
    auto shifted = emit(O::SHL,{part,constant(index*op.lane,8)},op.vector);
    result = emit(O::OR,{result,shifted},op.vector);
  }
  writeScalar(*destination,result,address,out,tmp);
}

void dragon::arm::ARMIGNILLifter::liftFpOp(const llvm::MCInst &mc, const FpOp &op,
    std::uint64_t address, ignil::Block &out, std::uint32_t &tmp) const {
  using O = ignil::Opcode;
  using F = FpKind;
  const auto width = op.width;
  auto emit = [&](O code, std::vector<ignil::Value> sources, ignil::Width bits) {
    auto result = newTemp(tmp,bits);
    out.append({code,result,std::move(sources),address});
    return result;
  };
  auto c = [](uint64_t value, ignil::Width bits) -> ignil::Value { return ignil::Const{value,bits}; };
  auto reg = [&](unsigned index) -> ignil::Value {
    const auto value = toReg(mc.getOperand(index).getReg());
    if (!value) { out.noteUnlifted(address); return emit(O::UNDEF,{},width); }
    return isZeroReg(*value) ? c(0,value->width) : ignil::Value{*value};
  };
  auto select = [&](ignil::Value condition, ignil::Value a, ignil::Value b, ignil::Width bits) {
    auto mask = emit(O::NEG,{emit(O::ZEXT,{condition},bits)},bits);
    auto left = emit(O::AND,{a,mask},bits);
    auto right = emit(O::AND,{b,emit(O::NOT,{mask},bits)},bits);
    return emit(O::OR,{left,right},bits);
  };
  const auto less = width == 32 ? O::FLT32 : O::FLT;
  const auto unordered = width == 32 ? O::FUNO32 : O::FUNO;
  if (op.kind == F::Compare) {
    auto a = reg(0), b = op.zero ? c(0,width) : reg(1);
    auto n = emit(less,{a,b},1);
    auto z = emit(width == 32 ? O::FEQ32 : O::FEQ,{a,b},1);
    auto v = emit(unordered,{a,b},1);
    auto carry = emit(O::XOR,{n,c(1,1)},1);
    for (const auto &[destination,value] : std::array<std::pair<ignil::Reg,ignil::Value>,4>{
             {{regNF_,n},{regZF_,z},{regCF_,carry},{regVF_,v}}})
      out.append({O::COPY,destination,{value},address});
    return;
  }
  const auto destination = toReg(mc.getOperand(0).getReg());
  if (!destination) { out.noteUnlifted(address); return; }
  auto source = reg(1);
  ignil::Value result = source;
  switch (op.kind) {
    case F::Add: case F::Sub: case F::Mul: case F::Div: {
      const auto code = op.kind == F::Add ? (width == 32 ? O::FADD32 : O::FADD)
                        : op.kind == F::Sub ? (width == 32 ? O::FSUB32 : O::FSUB)
                        : op.kind == F::Mul ? (width == 32 ? O::FMUL32 : O::FMUL)
                                           : (width == 32 ? O::FDIV32 : O::FDIV);
      result = emit(code,{source,reg(2)},width);
      break;
    }
    case F::Neg: result = emit(O::XOR,{source,c(1ull << (width-1),width)},width); break;
    case F::Abs: result = emit(O::AND,{source,c((1ull << (width-1))-1,width)},width); break;
    case F::Floor: case F::Ceil: case F::Trunc: case F::Sqrt: {
      const auto code = op.kind == F::Floor ? (width == 32 ? O::FFLOOR32 : O::FFLOOR)
                        : op.kind == F::Ceil ? (width == 32 ? O::FCEIL32 : O::FCEIL)
                        : op.kind == F::Trunc ? (width == 32 ? O::FTRUNC32 : O::FTRUNC)
                                             : (width == 32 ? O::FSQRT32 : O::FSQRT);
      result = emit(code,{source},width);
      break;
    }
    case F::Extend: result = emit(O::FPEXT,{source},64); break;
    case F::Narrow: result = emit(O::FPTRUNC,{source},32); break;
    case F::Select:
      result = select(emitCondition(mc.getOperand(3).getImm(),address,out,tmp),source,reg(2),width);
      break;
    case F::FromSigned: case F::FromUnsigned:
      result = emit(op.kind == F::FromSigned ? (width == 32 ? O::SITOFP32 : O::SITOFP)
                                           : (width == 32 ? O::UITOFP32 : O::UITOFP),{source},width);
      break;
    case F::ToSigned: case F::ToUnsigned: {
      const bool signedResult = op.kind == F::ToSigned;
      const unsigned bits = destination->width;
      const auto exponent = signedResult ? bits-1 : bits;
      const auto positive = width == 64 ? uint64_t(1023+exponent) << 52
                                        : uint64_t(127+exponent) << 23;
      const auto negative = signedResult ? positive | (1ull << (width-1)) : 0;
      auto nan = emit(unordered,{source,source},1);
      auto tooLow = emit(less,{source,c(negative,width)},1);
      auto tooHigh = emit(O::XOR,{emit(less,{source,c(positive,width)},1),c(1,1)},1);
      auto bad = emit(O::OR,{nan,emit(O::OR,{tooLow,tooHigh},1)},1);
      // Avoid an invalid LLVM fptosi/fptoui even on the discarded path.
      auto safe = select(bad,c(0,width),source,width);
      result = emit(signedResult ? (width == 32 ? O::FPTOSI32 : O::FPTOSI)
                                 : (width == 32 ? O::FPTOUI32 : O::FPTOUI),{safe},bits);
      const uint64_t minimum = signedResult ? 1ull << (bits-1) : 0;
      const uint64_t maximum = signedResult ? (1ull << (bits-1))-1 : maskToWidth(~0ull,bits);
      result = select(tooLow,c(minimum,bits),result,bits);
      result = select(tooHigh,c(maximum,bits),result,bits);
      result = select(nan,c(0,bits),result,bits);
      break;
    }
    default: out.noteUnlifted(address); emitUndef(*destination,address,out); return;
  }
  writeScalar(*destination,result,address,out,tmp);
}

void dragon::arm::ARMIGNILLifter::liftIntOp(const llvm::MCInst &mc,
                                            const IntOp &op,
                                            std::uint64_t addr,
                                            ignil::Block &out,
                                            std::uint32_t &tmp) const {
  using I = IntKind;
  using Opc = ignil::Opcode;
  const ignil::Width w = op.width;

  // Register operand `idx` as a value of `width` bits (XZR/WZR read 0).
  auto val = [&](unsigned idx, ignil::Width width) -> ignil::Value {
    auto r = toReg(mc.getOperand(idx).getReg());
    if (!r || isZeroReg(*r))
      return ignil::Const{0, width};
    return *r;
  };
  auto emit = [&](Opc o, std::vector<ignil::Value> srcs, ignil::Width width) {
    auto t = newTemp(tmp, width);
    out.append({o, t, std::move(srcs), addr});
    return t;
  };
  auto c = [](std::uint64_t v, ignil::Width width) {
    return ignil::Value{ignil::Const{v, width}};
  };
  auto writeDst = [&](ignil::Value v) {
    auto d = toReg(mc.getOperand(0).getReg());
    if (d && !isZeroReg(*d))
      out.append({Opc::COPY, *d, {std::move(v)}, addr});
  };
  // cond ? a : b, with a mask (IGNIL has no select).
  auto select = [&](ignil::Temp cond, ignil::Value a, ignil::Value b,
                    ignil::Width width) {
    auto m = emit(Opc::NEG, {emit(Opc::ZEXT, {cond}, width)}, width);
    auto x = emit(Opc::AND, {std::move(a), m}, width);
    auto y = emit(Opc::AND, {std::move(b), emit(Opc::NOT, {m}, width)}, width);
    return emit(Opc::OR, {x, y}, width);
  };

  switch (op.kind) {
    case I::Clz: {
      ignil::Value value = val(1,w), count = c(0,w);
      for (unsigned bits = w/2; bits; bits /= 2) {
        auto top = emit(Opc::SHR,{value,c(w-bits,8)},w);
        auto zero = emit(Opc::EQ,{top,c(0,w)},1);
        auto shifted = emit(Opc::SHL,{value,c(bits,8)},w);
        value = select(zero,shifted,value,w);
        count = emit(Opc::ADD,{count,select(zero,c(bits,w),c(0,w),w)},w);
      }
      auto zero = emit(Opc::EQ,{value,c(0,w)},1);
      writeDst(emit(Opc::ADD,{count,emit(Opc::ZEXT,{zero},w)},w));
      return;
    }
    case I::Rbit: {
      const auto input = val(1,w);
      ignil::Value result = c(0,w);
      for (unsigned bit = 0; bit < w; ++bit) {
        auto shifted = emit(Opc::SHR,{input,c(bit,8)},w);
        auto low = emit(Opc::AND,{shifted,c(1,w)},w);
        auto reversed = emit(Opc::SHL,{low,c(w-1-bit,8)},w);
        result = emit(Opc::OR,{result,reversed},w);
      }
      writeDst(result);
      return;
    }
    case I::Bic:
    case I::Bics:
    case I::Orn:
    case I::Eon: {
      auto rhs = emit(Opc::NOT, {emitShiftedReg(mc, 2, 3, w, addr, out, tmp)},
                      w);
      const Opc o = op.kind == I::Orn   ? Opc::OR
                    : op.kind == I::Eon ? Opc::XOR
                                        : Opc::AND;
      auto r = emit(o, {val(1, w), rhs}, w);
      writeDst(r);
      if (op.kind == I::Bics)
        emitArithFlags(addr, out, tmp,
                       {
                               {ARMFlag::C, cfAlwaysZero(addr)},
                               {ARMFlag::Z, zfEqZero(r, addr)},
                               {ARMFlag::N, nfSignBit(r, addr)},
                               {ARMFlag::V, vfAlwaysZero(addr)},
                       });
      return;
    }

    case I::Ubfm:
    case I::Sbfm: {
      // Bitfield move. With s = w-1-imms: when imms >= immr the field
      // Rn[imms:immr] is extracted to bit 0 - (Rn << s) >> (s + immr); else
      // Rn[imms:0] is inserted at bit w-immr - ((Rn << s) >> s) << (w-immr).
      // The right shift is arithmetic for SBFM. lsl/lsr/asr #n, sxtb/h/w,
      // uxtb/h, ubfx/sbfx and ubfiz/sbfiz are all this.
      const auto immr = static_cast<unsigned>(mc.getOperand(2).getImm());
      const auto imms = static_cast<unsigned>(mc.getOperand(3).getImm());
      const Opc right = op.kind == I::Sbfm ? Opc::SAR : Opc::SHR;
      const unsigned sh = w - 1 - imms;
      ignil::Value v = val(1, w);
      if (sh)
        v = emit(Opc::SHL, {v, c(sh, 8)}, w);
      if (imms >= immr) {
        if (sh + immr)
          v = emit(right, {v, c(sh + immr, 8)}, w);
      } else {
        if (sh)
          v = emit(right, {v, c(sh, 8)}, w);
        v = emit(Opc::SHL, {v, c(w - immr, 8)}, w);
      }
      writeDst(v);
      return;
    }

    case I::Bfm: {
      // op[0]=Rd, op[1]=Rd (tied), op[2]=Rn, op[3]=immr, op[4]=imms. The
      // field - Rn[imms:immr] to bit 0 (bfxil) or Rn[imms:0] to bit w-immr
      // (bfi) - replaces those bits of Rd; the rest of Rd stays.
      const auto immr = static_cast<unsigned>(mc.getOperand(3).getImm());
      const auto imms = static_cast<unsigned>(mc.getOperand(4).getImm());
      unsigned len, pos, from;
      if (imms >= immr) {
        len = imms - immr + 1;
        pos = 0;
        from = immr;
      } else {
        len = imms + 1;
        pos = w - immr;
        from = 0;
      }
      const std::uint64_t low = len >= 64 ? ~0ull : (1ull << len) - 1;
      const std::uint64_t mask = (low << pos) & (w >= 64 ? ~0ull : (1ull << w) - 1);
      ignil::Value field = val(2, w);
      if (from)
        field = emit(Opc::SHR, {field, c(from, 8)}, w);
      field = emit(Opc::AND, {field, c(low, w)}, w);
      if (pos)
        field = emit(Opc::SHL, {field, c(pos, 8)}, w);
      auto kept = emit(Opc::AND, {val(1, w), c(~mask, w)}, w);
      writeDst(emit(Opc::OR, {kept, field}, w));
      return;
    }

    case I::Lslv:
    case I::Lsrv:
    case I::Asrv:
    case I::Rorv: {
      // The amount is Rm modulo the width.
      auto n = emit(Opc::AND, {val(2, w), c(w - 1, w)}, w);
      ignil::Value x = val(1, w);
      if (op.kind == I::Rorv) {
        auto hi = emit(Opc::SHR, {x, n}, w);
        auto back = emit(Opc::AND, {emit(Opc::SUB, {c(w, w), n}, w),
                                    c(w - 1, w)},
                         w);
        auto lo = emit(Opc::SHL, {x, back}, w);
        writeDst(emit(Opc::OR, {hi, lo}, w));
        return;
      }
      const Opc o = op.kind == I::Lslv   ? Opc::SHL
                    : op.kind == I::Lsrv ? Opc::SHR
                                         : Opc::SAR;
      writeDst(emit(o, {x, n}, w));
      return;
    }

    case I::Csel:
    case I::Csinc:
    case I::Csinv:
    case I::Csneg: {
      const auto cc = static_cast<unsigned>(mc.getOperand(3).getImm());
      auto cond = emitCondition(cc, addr, out, tmp);
      ignil::Value b = val(2, w);
      if (op.kind == I::Csinc)
        b = emit(Opc::ADD, {b, c(1, w)}, w);
      else if (op.kind == I::Csinv)
        b = emit(Opc::NOT, {b}, w);
      else if (op.kind == I::Csneg)
        b = emit(Opc::NEG, {b}, w);
      writeDst(select(cond, val(1, w), b, w));
      return;
    }

    case I::Ccmp:
    case I::Ccmn: {
      // cond ? flags(Rn -/+ op2) : #nzcv
      const auto cc = static_cast<unsigned>(mc.getOperand(3).getImm());
      const auto nzcv = static_cast<unsigned>(mc.getOperand(2).getImm());
      auto cond = emitCondition(cc, addr, out, tmp);
      ignil::Value lhs = val(0, w);
      ignil::Value rhs =
              op.immForm ? c(static_cast<std::uint64_t>(mc.getOperand(1).getImm()),
                             w)
                         : val(1, w);
      auto lhsT = emit(Opc::COPY, {lhs}, w);
      auto rhsT = emit(Opc::COPY, {rhs}, w);
      const bool isAdd = op.kind == I::Ccmn;
      auto res = emit(isAdd ? Opc::ADD : Opc::SUB, {lhsT, rhsT}, w);
      auto n = emit(Opc::SLT, {res, c(0, w)}, 1);
      auto z = emit(Opc::EQ, {res, c(0, w)}, 1);
      auto carry = isAdd ? emit(Opc::ULT, {res, lhsT}, 1)
                         : emit(Opc::UGE, {lhsT, rhsT}, 1);
      // V: operands of the same sign (add) / different signs (sub), result
      // of the other sign.
      auto ab = emit(Opc::XOR, {lhsT, rhsT}, w);
      auto ar = emit(Opc::XOR, {lhsT, res}, w);
      auto vbits = emit(Opc::AND, {isAdd ? ignil::Value{emit(Opc::NOT, {ab}, w)}
                                         : ignil::Value{ab},
                                   ar},
                        w);
      auto v = emit(Opc::SLT, {vbits, c(0, w)}, 1);
      const std::pair<const ignil::Reg *, std::pair<ignil::Temp, unsigned>>
              flags[] = {{&regNF_, {n, 3}}, {&regZF_, {z, 2}},
                         {&regCF_, {carry, 1}}, {&regVF_, {v, 0}}};
      for (const auto &[reg, fv]: flags) {
        if (!reg->width)
          continue;
        auto computed = emit(Opc::ZEXT, {fv.first}, reg->width);
        auto chosen = select(cond, computed, c((nzcv >> fv.second) & 1,
                                               reg->width),
                             reg->width);
        out.append({Opc::COPY, *reg, {chosen}, addr});
      }
      return;
    }

    case I::Madd:
    case I::Msub: {
      auto prod = emit(Opc::MUL, {val(1, w), val(2, w)}, w);
      writeDst(emit(op.kind == I::Madd ? Opc::ADD : Opc::SUB, {val(3, w), prod},
                    w));
      return;
    }
    case I::Smaddl:
    case I::Umaddl:
    case I::Smsubl:
    case I::Umsubl: {
      const bool sgn = op.kind == I::Smaddl || op.kind == I::Smsubl;
      const Opc ext = sgn ? Opc::SEXT : Opc::ZEXT;
      auto a = emit(ext, {val(1, 32)}, 64);
      auto b = emit(ext, {val(2, 32)}, 64);
      auto prod = emit(Opc::MUL, {a, b}, 64);
      const bool add = op.kind == I::Smaddl || op.kind == I::Umaddl;
      writeDst(emit(add ? Opc::ADD : Opc::SUB, {val(3, 64), prod}, 64));
      return;
    }
    case I::Smulh:
    case I::Umulh: {
      const Opc ext = op.kind == I::Smulh ? Opc::SEXT : Opc::ZEXT;
      auto a = emit(ext, {val(1, 64)}, 128);
      auto b = emit(ext, {val(2, 64)}, 128);
      auto prod = emit(Opc::MUL, {a, b}, 128);
      auto hi = emit(Opc::SHR, {prod, c(64, 8)}, 128);
      writeDst(emit(Opc::TRUNC, {hi}, 64));
      return;
    }

    case I::Udiv:
    case I::Sdiv: {
      // Division by zero gives 0; INT_MIN / -1 wraps to INT_MIN (as SDIV).
      auto n = emit(Opc::COPY, {val(1, w)}, w);
      auto d = emit(Opc::COPY, {val(2, w)}, w);
      auto zero = emit(Opc::EQ, {d, c(0, w)}, 1);
      // Divide by 1 instead of 0 so no op sees a zero divisor.
      auto safe = select(zero, c(1, w), d, w);
      auto q = emit(op.kind == I::Udiv ? Opc::UDIV : Opc::SDIV, {n, safe}, w);
      writeDst(select(zero, c(0, w), q, w));
      return;
    }

    case I::Extr: {
      const auto lsb = static_cast<unsigned>(mc.getOperand(3).getImm());
      if (lsb == 0) {
        writeDst(emit(Opc::COPY, {val(2, w)}, w));
        return;
      }
      auto lo = emit(Opc::SHR, {val(2, w), c(lsb, 8)}, w);
      auto hi = emit(Opc::SHL, {val(1, w), c(w - lsb, 8)}, w);
      writeDst(emit(Opc::OR, {lo, hi}, w));
      return;
    }

    case I::Rev:
    case I::Rev16:
    case I::Rev32: {
      // Reverse the bytes within each container of `group` bytes.
      const unsigned group = op.kind == I::Rev16 ? 2
                             : op.kind == I::Rev32 ? 4
                                                   : w / 8;
      ignil::Value x = val(1, w);
      std::optional<ignil::Temp> acc;
      for (unsigned i = 0; i < w / 8; ++i) {
        const unsigned base = i / group * group;
        const unsigned j = base + (group - 1 - (i - base)); // destination byte
        ignil::Value byte = x;
        if (i)
          byte = emit(Opc::SHR, {byte, c(8 * i, 8)}, w);
        byte = emit(Opc::AND, {byte, c(0xff, w)}, w);
        if (j)
          byte = emit(Opc::SHL, {byte, c(8 * j, 8)}, w);
        acc = acc ? emit(Opc::OR, {*acc, byte}, w)
                  : emit(Opc::COPY, {byte}, w);
      }
      writeDst(*acc);
      return;
    }
  }
}

void dragon::arm::ARMIGNILLifter::liftAddSub(const llvm::MCInst &mc,
                                             std::uint64_t addr,
                                             ignil::Block &out,
                                             std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();
  bool isSub =
          (opc == opSUBWrr_ || opc == opSUBXrr_ || opc == opSUBWri_ ||
           opc == opSUBXri_ || opc == opSUBWrs_ || opc == opSUBXrs_ ||
           opc == opSUBSWrr_ || opc == opSUBSXrr_ || opc == opSUBSWri_ ||
           opc == opSUBSXri_ || opc == opSUBSWrs_ || opc == opSUBSXrs_);
  bool setFlags =
          (opc == opADDSWrr_ || opc == opADDSXrr_ || opc == opADDSWri_ ||
           opc == opADDSXri_ || opc == opADDSWrs_ || opc == opADDSXrs_ ||
           opc == opSUBSWrr_ || opc == opSUBSXrr_ || opc == opSUBSWri_ ||
           opc == opSUBSXri_ || opc == opSUBSWrs_ || opc == opSUBSXrs_);
  const bool isImmForm =
          (opc == opADDWri_ || opc == opADDXri_ || opc == opADDSWri_ ||
           opc == opADDSXri_ || opc == opSUBWri_ || opc == opSUBXri_ ||
           opc == opSUBSWri_ || opc == opSUBSXri_);
  const bool isShiftedForm =
          (opc == opADDWrs_ || opc == opADDXrs_ || opc == opADDSWrs_ ||
           opc == opADDSXrs_ || opc == opSUBWrs_ || opc == opSUBXrs_ ||
           opc == opSUBSWrs_ || opc == opSUBSXrs_);
  const auto ext = extAddSub_.find(opc);
  const bool isExtForm = ext != extAddSub_.end();
  if (isExtForm) {
    isSub = ext->second.isSub;
    setFlags = ext->second.setFlags;
  }

  // op[0]=dst, op[1]=Rn(lhs) - AArch64 ADD/SUB is 3-address, unlike x86's
  // tied dst/src1, so there is no "save dst before overwrite" step here.
  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftAddSub in addr {:#x} no dst", addr);
    return;
  }
  auto lhsReg = toReg(mc.getOperand(1).getReg());
  if (!lhsReg) {
    logger_.log("Error liftAddSub in addr {:#x} no lhs", addr);
    emitUndef(*dst, addr, out);
    return;
  }
  // In the extended-register form register 31 as Rn is SP, never XZR (LLVM
  // already decodes it as SP, which is not the zero register's offset).
  ignil::Value lhs = isZeroReg(*lhsReg)
                             ? ignil::Value{ignil::Const{0, dst->width}}
                             : ignil::Value{*lhsReg};

  ignil::Value rhs;
  if (isExtForm) {
    rhs = emitExtendedReg(mc, 2, 3, dst->width, addr, out, tmp);
  } else if (isImmForm) {
    // op[2]=12-bit imm, op[3]=shift (0 or 12, meaning imm<<12).
    auto imm = static_cast<std::uint64_t>(mc.getOperand(2).getImm());
    auto shift = static_cast<std::uint64_t>(mc.getOperand(3).getImm());
    rhs = ignil::Const{imm << shift, dst->width};
  } else if (isShiftedForm) {
    rhs = emitShiftedReg(mc, 2, 3, dst->width, addr, out, tmp);
  } else {
    auto rhsReg = toReg(mc.getOperand(2).getReg());
    rhs = (!rhsReg || isZeroReg(*rhsReg))
                  ? ignil::Value{ignil::Const{0, dst->width}}
                  : ignil::Value{*rhsReg};
  }

  // The flags below read the operands after Rd has been written; when Rd
  // is also Rn or Rm (`subs w20, w20, #1`, the usual loop counter) they
  // must see the old value, not the result. Take copies first.
  if (setFlags) {
    if (std::holds_alternative<ignil::Reg>(lhs)) {
      auto t = newTemp(tmp, dst->width);
      out.append({ignil::Opcode::COPY, t, {lhs}, addr});
      lhs = t;
    }
    if (std::holds_alternative<ignil::Reg>(rhs)) {
      auto t = newTemp(tmp, dst->width);
      out.append({ignil::Opcode::COPY, t, {rhs}, addr});
      rhs = t;
    }
  }

  auto result = newTemp(tmp, dst->width);
  out.append({isSub ? ignil::Opcode::SUB : ignil::Opcode::ADD,
              result,
              {lhs, rhs},
              addr});

  // A write to XZR/WZR is architecturally discarded - this is exactly what
  // makes CMP (SUBS, Rd=zero) and CMN (ADDS, Rd=zero) fall out of this same
  // generic function for free, with no dedicated liftCmp needed.
  if (!isZeroReg(*dst))
    out.append({ignil::Opcode::COPY, *dst, {result}, addr});

  // Only S-suffixed opcodes touch NZCV at all; plain ADD/SUB leave flags
  // completely untouched (no Op emitted), unlike x86 where every arith op
  // affects EFLAGS.
  if (setFlags) {
    if (isSub)
      emitArithFlags(
              addr, out, tmp,
              {
                      {ARMFlag::C, cfSubNoBorrow(lhs, rhs, addr)},
                      {ARMFlag::Z, zfEqZero(result, addr)},
                      {ARMFlag::N, nfSignBit(result, addr)},
                      {ARMFlag::V, ofSubOverflow(lhs, rhs, result, addr)},
              });
    else
      emitArithFlags(
              addr, out, tmp,
              {
                      {ARMFlag::C, cfAddOverflow(result, rhs, addr)},
                      {ARMFlag::Z, zfEqZero(result, addr)},
                      {ARMFlag::N, nfSignBit(result, addr)},
                      {ARMFlag::V, ofAddOverflow(lhs, rhs, result, addr)},
              });
  }
}

void dragon::arm::ARMIGNILLifter::liftLogic(const llvm::MCInst &mc,
                                            std::uint64_t addr,
                                            ignil::Block &out,
                                            std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();

  ignil::Opcode irOp;
  if (opc == opANDWrr_ || opc == opANDXrr_ || opc == opANDWri_ ||
      opc == opANDXri_ || opc == opANDWrs_ || opc == opANDXrs_ ||
      opc == opANDSWri_ || opc == opANDSXri_ || opc == opANDSWrs_ ||
      opc == opANDSXrs_)
    irOp = ignil::Opcode::AND;
  else if (opc == opORRWrr_ || opc == opORRXrr_ || opc == opORRWri_ ||
           opc == opORRXri_ || opc == opORRWrs_ || opc == opORRXrs_)
    irOp = ignil::Opcode::OR;
  else
    irOp = ignil::Opcode::XOR;

  // Only AND has S-suffixed forms (ANDS) - ORR/EOR never set flags at all,
  // and (per the constructor's opcode table) AArch64 has no ANDSWrr/ANDSXrr,
  // only the ri/rs S-forms.
  const bool setFlags = (opc == opANDSWri_ || opc == opANDSXri_ ||
                         opc == opANDSWrs_ || opc == opANDSXrs_);
  const bool isImmForm =
          (opc == opANDWri_ || opc == opANDXri_ || opc == opANDSWri_ ||
           opc == opANDSXri_ || opc == opORRWri_ || opc == opORRXri_ ||
           opc == opEORWri_ || opc == opEORXri_);
  const bool isPlainRr =
          (opc == opANDWrr_ || opc == opANDXrr_ || opc == opORRWrr_ ||
           opc == opORRXrr_ || opc == opEORWrr_ || opc == opEORXrr_);

  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftLogic in addr {:#x} no dst", addr);
    return;
  }
  auto lhsReg = toReg(mc.getOperand(1).getReg());
  if (!lhsReg) {
    logger_.log("Error liftLogic in addr {:#x} no lhs", addr);
    emitUndef(*dst, addr, out);
    return;
  }
  ignil::Value lhs = isZeroReg(*lhsReg)
                             ? ignil::Value{ignil::Const{0, dst->width}}
                             : ignil::Value{*lhsReg};

  ignil::Value rhs;
  if (isImmForm) {
    auto encoded = static_cast<std::uint64_t>(mc.getOperand(2).getImm());
    auto decoded = decodeLogicalImmediate(encoded, dst->width);
    rhs = ignil::Const{decoded, dst->width};
  } else if (isPlainRr) {
    auto rhsReg = toReg(mc.getOperand(2).getReg());
    rhs = (!rhsReg || isZeroReg(*rhsReg))
                  ? ignil::Value{ignil::Const{0, dst->width}}
                  : ignil::Value{*rhsReg};
  } else {
    // rs form - also where the "mov reg,reg" ORR alias (Rn=XZR, shift=0)
    // falls out for free via the lhs zero-reg handling above.
    rhs = emitShiftedReg(mc, 2, 3, dst->width, addr, out, tmp);
  }

  auto result = newTemp(tmp, dst->width);
  out.append({irOp, result, {lhs, rhs}, addr});

  // Discarded write covers TST (ANDS, Rd=zero); MOV (ORR, Rn=XZR) already
  // has a real dst so it takes this branch normally.
  if (!isZeroReg(*dst))
    out.append({ignil::Opcode::COPY, *dst, {result}, addr});

  if (setFlags)
    // ANDS: C and V are architecturally hardwired to 0 (logical ops never
    // carry/overflow); only Z/N are actually computed from the result.
    emitArithFlags(addr, out, tmp,
                   {
                           {ARMFlag::C, cfAlwaysZero(addr)},
                           {ARMFlag::Z, zfEqZero(result, addr)},
                           {ARMFlag::N, nfSignBit(result, addr)},
                           {ARMFlag::V, vfAlwaysZero(addr)},
                   });
}

dragon::ignil::Temp dragon::arm::ARMIGNILLifter::emitAddress(
        const llvm::MCInst &mc, unsigned opStart, std::int64_t scale,
        ignil::Width ptrWidth, std::uint64_t addr, ignil::Block &out,
        std::uint32_t &tmp) const {
  // mc.getOperand(opStart)=base register, mc.getOperand(opStart+1)=offset
  // immediate. Reused for LDR/STR *ui (scale=element size), single LDR/STR
  // pre/post (scale=1, immediate already byte-granular), and LDP/STP in all
  // three forms (scale=element size - LDP/STP immediates are always scaled,
  // unlike single-register pre/post).
  auto base = toReg(mc.getOperand(opStart).getReg());
  auto imm = mc.getOperand(opStart + 1).getImm();

  ignil::Value baseVal = (!base || isZeroReg(*base))
                                 ? ignil::Value{ignil::Const{0, ptrWidth}}
                                 : ignil::Value{*base};

  auto result = newTemp(tmp, ptrWidth);
  if (imm == 0) {
    out.append({ignil::Opcode::COPY, result, {baseVal}, addr});
    return result;
  }

  const auto offset = static_cast<std::uint64_t>(imm * scale);
  out.append({ignil::Opcode::ADD,
              result,
              {baseVal, ignil::Const{offset, ptrWidth}},
              addr});
  return result;
}

void dragon::arm::ARMIGNILLifter::liftLoad(const llvm::MCInst &mc,
                                           std::uint64_t addr,
                                           ignil::Block &out,
                                           std::uint32_t &tmp, ignil::Width widthOverride) const {
  const unsigned opc = mc.getOpcode();

  ignil::Width memWidth;
  std::int64_t scale;
  bool signExtend = false;
  bool isPrePost = false;
  bool isPost = false;

  if (opc == opLDRWui_) {
    memWidth = 32;
    scale = 4;
  } else if (opc == opLDRXui_) {
    memWidth = 64;
    scale = 8;
  } else if (opc == opLDRBui_ || opc == opLDRBBui_) {
    memWidth = 8;
    scale = 1;
  } else if (opc == opLDRHui_ || opc == opLDRHHui_) {
    memWidth = 16;
    scale = 2;
  } else if (opc == opLDRSBWui_ || opc == opLDRSBXui_) {
    memWidth = 8;
    scale = 1;
    signExtend = true;
  } else if (opc == opLDRSHWui_ || opc == opLDRSHXui_) {
    memWidth = 16;
    scale = 2;
    signExtend = true;
  } else if (opc == opLDRSWui_) {
    memWidth = 32;
    scale = 4;
    signExtend = true;
  } else if (opc == opLDRWpre_ || opc == opLDRWpost_) {
    memWidth = 32;
    scale = 1; // single-register pre/post immediate is raw bytes, not scaled
    isPrePost = true;
    isPost = (opc == opLDRWpost_);
  } else if (opc == opLDRXpre_ || opc == opLDRXpost_) {
    memWidth = 64;
    scale = 1;
    isPrePost = true;
    isPost = (opc == opLDRXpost_);
  } else {
    logger_.log("Error liftLoad in addr {:#x} unhandled opcode", addr);
    return;
  }

  // *ui: op[0]=dst, op[1]=Rn, op[2]=imm. pre/post: op[0]=writeback(=Rn),
  // op[1]=dst, op[2]=Rn, op[3]=imm.
  if (widthOverride) {
    memWidth = widthOverride;
    if (!isPrePost) scale = widthOverride / 8;
  }
  const unsigned dstOpIdx = isPrePost ? 1 : 0;
  const unsigned baseOpIdx = isPrePost ? 2 : 1;

  auto dst = toReg(mc.getOperand(dstOpIdx).getReg());
  if (!dst) {
    logger_.log("Error liftLoad in addr {:#x} no dst", addr);
    return;
  }

  constexpr ignil::Width ptrWidth = 64; // AArch64 pointers are always 64-bit
  ignil::Temp loadAddr;
  ignil::Temp writebackAddr;

  if (isPrePost) {
    if (isPost) {
      // Post-index: the transfer uses the base as-is; the writeback address
      // (base+offset) is computed separately and only applied afterward.
      auto baseReg = toReg(mc.getOperand(baseOpIdx).getReg());
      if (!baseReg) {
        logger_.log("Error liftLoad in addr {:#x} no base", addr);
        emitUndef(*dst, addr, out);
        return;
      }
      loadAddr = newTemp(tmp, ptrWidth);
      out.append({ignil::Opcode::COPY, loadAddr, {*baseReg}, addr});
      writebackAddr =
              emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
    } else {
      // Pre-index: the transfer address IS base+offset, which is also
      // exactly the value written back afterward.
      loadAddr = emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
      writebackAddr = loadAddr;
    }
  } else {
    loadAddr = emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
  }

  auto loaded = newTemp(tmp, memWidth);
  out.append({ignil::Opcode::LOAD, loaded, {loadAddr}, addr});

  if (memWidth < dst->width) {
    auto extended = newTemp(tmp, dst->width);
    out.append({signExtend ? ignil::Opcode::SEXT : ignil::Opcode::ZEXT,
                extended,
                {loaded},
                addr});
    loaded = extended;
  }

  if (!isZeroReg(*dst))
    writeScalar(*dst, loaded, addr, out, tmp);

  if (isPrePost) {
    auto baseReg = toReg(mc.getOperand(baseOpIdx).getReg());
    if (baseReg)
      out.append({ignil::Opcode::COPY, *baseReg, {writebackAddr}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftStore(const llvm::MCInst &mc,
                                            std::uint64_t addr,
                                            ignil::Block &out,
                                            std::uint32_t &tmp, ignil::Width widthOverride) const {
  const unsigned opc = mc.getOpcode();

  ignil::Width memWidth;
  std::int64_t scale;
  bool isPrePost = false;
  bool isPost = false;

  if (opc == opSTRWui_) {
    memWidth = 32;
    scale = 4;
  } else if (opc == opSTRXui_) {
    memWidth = 64;
    scale = 8;
  } else if (opc == opSTRBui_ || opc == opSTRBBui_) {
    memWidth = 8;
    scale = 1;
  } else if (opc == opSTRHui_ || opc == opSTRHHui_) {
    memWidth = 16;
    scale = 2;
  } else if (opc == opSTRWpre_ || opc == opSTRWpost_) {
    memWidth = 32;
    scale = 1;
    isPrePost = true;
    isPost = (opc == opSTRWpost_);
  } else if (opc == opSTRXpre_ || opc == opSTRXpost_) {
    memWidth = 64;
    scale = 1;
    isPrePost = true;
    isPost = (opc == opSTRXpost_);
  } else {
    logger_.log("Error liftStore in addr {:#x} unhandled opcode", addr);
    return;
  }

  // *ui: op[0]=Rt(src), op[1]=Rn, op[2]=imm. pre/post: op[0]=writeback(=Rn),
  // op[1]=Rt(src), op[2]=Rn, op[3]=imm.
  if (widthOverride) {
    memWidth = widthOverride;
    if (!isPrePost) scale = widthOverride / 8;
  }
  const unsigned srcOpIdx = isPrePost ? 1 : 0;
  const unsigned baseOpIdx = isPrePost ? 2 : 1;

  auto srcReg = toReg(mc.getOperand(srcOpIdx).getReg());
  if (!srcReg) {
    logger_.log("Error liftStore in addr {:#x} no src", addr);
    return;
  }

  ignil::Value src = isZeroReg(*srcReg)
                             ? ignil::Value{ignil::Const{0, memWidth}}
                             : ignil::Value{*srcReg};
  if (srcReg->width > memWidth) {
    auto truncated = newTemp(tmp, memWidth);
    out.append({ignil::Opcode::TRUNC, truncated, {src}, addr});
    src = truncated;
  }

  constexpr ignil::Width ptrWidth = 64;
  ignil::Temp storeAddr;
  ignil::Temp writebackAddr;

  if (isPrePost) {
    if (isPost) {
      auto baseReg = toReg(mc.getOperand(baseOpIdx).getReg());
      if (!baseReg) {
        logger_.log("Error liftStore in addr {:#x} no base", addr);
        return;
      }
      storeAddr = newTemp(tmp, ptrWidth);
      out.append({ignil::Opcode::COPY, storeAddr, {*baseReg}, addr});
      writebackAddr =
              emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
    } else {
      storeAddr = emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
      writebackAddr = storeAddr;
    }
  } else {
    storeAddr = emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
  }

  out.append({ignil::Opcode::STORE, std::nullopt, {storeAddr, src}, addr});

  if (isPrePost) {
    auto baseReg = toReg(mc.getOperand(baseOpIdx).getReg());
    if (baseReg)
      out.append({ignil::Opcode::COPY, *baseReg, {writebackAddr}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftLoadPair(const llvm::MCInst &mc,
                                               std::uint64_t addr,
                                               ignil::Block &out,
                                               std::uint32_t &tmp, ignil::Width widthOverride) const {
  const unsigned opc = mc.getOpcode();

  ignil::Width elemWidth;
  std::int64_t scale;
  bool isPre = false;
  bool isPost = false;

  if (opc == opLDPWi_) {
    elemWidth = 32;
    scale = 4;
  } else if (opc == opLDPXi_) {
    elemWidth = 64;
    scale = 8;
  } else if (opc == opLDPWpre_) {
    elemWidth = 32;
    scale = 4;
    isPre = true;
  } else if (opc == opLDPXpre_) {
    elemWidth = 64;
    scale = 8;
    isPre = true;
  } else if (opc == opLDPWpost_) {
    elemWidth = 32;
    scale = 4;
    isPost = true;
  } else if (opc == opLDPXpost_) {
    elemWidth = 64;
    scale = 8;
    isPost = true;
  } else {
    logger_.log("Error liftLoadPair in addr {:#x} unhandled opcode", addr);
    return;
  }

  if (widthOverride) { elemWidth = widthOverride; scale = widthOverride / 8; }
  const bool isPrePost = isPre || isPost;
  // offset form: op[0]=Rt1, op[1]=Rt2, op[2]=Rn, op[3]=imm.
  // pre/post form: op[0]=writeback(=Rn), op[1]=Rt1, op[2]=Rt2, op[3]=Rn,
  // op[4]=imm.
  const unsigned rt1Idx = isPrePost ? 1 : 0;
  const unsigned rt2Idx = isPrePost ? 2 : 1;
  const unsigned baseIdx = isPrePost ? 3 : 2;

  auto rt1 = toReg(mc.getOperand(rt1Idx).getReg());
  auto rt2 = toReg(mc.getOperand(rt2Idx).getReg());
  if (!rt1 || !rt2) {
    logger_.log("Error liftLoadPair in addr {:#x} bad Rt1/Rt2", addr);
    return;
  }
  if (widthOverride && rt1->offset == rt2->offset) {
    emitUndef(ignil::Reg{rt1->offset,128,rt1->name+"[V]"},addr,out);
    out.noteUnlifted(addr);
    return;
  }

  constexpr ignil::Width ptrWidth = 64;
  ignil::Temp loadAddr;
  ignil::Temp writebackAddr;

  if (isPost) {
    // LDP/STP immediates are always scaled by element size, in all three
    // forms - unlike single LDR/STR, where only the *ui (offset) form is
    // scaled and pre/post are raw bytes. Post here still uses the base
    // as-is for the transfer; only the writeback is offset.
    auto baseReg = toReg(mc.getOperand(baseIdx).getReg());
    if (!baseReg) {
      logger_.log("Error liftLoadPair in addr {:#x} no base", addr);
      return;
    }
    loadAddr = newTemp(tmp, ptrWidth);
    out.append({ignil::Opcode::COPY, loadAddr, {*baseReg}, addr});
    writebackAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
  } else if (isPre) {
    loadAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
    writebackAddr = loadAddr;
  } else {
    loadAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
  }

  const auto elemBytes = static_cast<std::uint64_t>(elemWidth / 8);

  auto loaded1 = newTemp(tmp, elemWidth);
  out.append({ignil::Opcode::LOAD, loaded1, {loadAddr}, addr});
  if (!isZeroReg(*rt1))
    writeScalar(*rt1, loaded1, addr, out, tmp);

  auto addr2 = newTemp(tmp, ptrWidth);
  out.append({ignil::Opcode::ADD,
              addr2,
              {loadAddr, ignil::Const{elemBytes, ptrWidth}},
              addr});
  auto loaded2 = newTemp(tmp, elemWidth);
  out.append({ignil::Opcode::LOAD, loaded2, {addr2}, addr});
  if (!isZeroReg(*rt2))
    writeScalar(*rt2, loaded2, addr, out, tmp);

  if (isPrePost) {
    auto baseReg = toReg(mc.getOperand(baseIdx).getReg());
    if (baseReg)
      out.append({ignil::Opcode::COPY, *baseReg, {writebackAddr}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftStorePair(const llvm::MCInst &mc,
                                                std::uint64_t addr,
                                                ignil::Block &out,
                                                std::uint32_t &tmp, ignil::Width widthOverride) const {
  const unsigned opc = mc.getOpcode();

  ignil::Width elemWidth;
  std::int64_t scale;
  bool isPre = false;
  bool isPost = false;

  if (opc == opSTPWi_) {
    elemWidth = 32;
    scale = 4;
  } else if (opc == opSTPXi_) {
    elemWidth = 64;
    scale = 8;
  } else if (opc == opSTPWpre_) {
    elemWidth = 32;
    scale = 4;
    isPre = true;
  } else if (opc == opSTPXpre_) {
    elemWidth = 64;
    scale = 8;
    isPre = true;
  } else if (opc == opSTPWpost_) {
    elemWidth = 32;
    scale = 4;
    isPost = true;
  } else if (opc == opSTPXpost_) {
    elemWidth = 64;
    scale = 8;
    isPost = true;
  } else {
    logger_.log("Error liftStorePair in addr {:#x} unhandled opcode", addr);
    return;
  }

  if (widthOverride) { elemWidth = widthOverride; scale = widthOverride / 8; }
  const bool isPrePost = isPre || isPost;
  const unsigned rt1Idx = isPrePost ? 1 : 0;
  const unsigned rt2Idx = isPrePost ? 2 : 1;
  const unsigned baseIdx = isPrePost ? 3 : 2;

  auto rt1 = toReg(mc.getOperand(rt1Idx).getReg());
  auto rt2 = toReg(mc.getOperand(rt2Idx).getReg());
  if (!rt1 || !rt2) {
    logger_.log("Error liftStorePair in addr {:#x} bad Rt1/Rt2", addr);
    return;
  }
  ignil::Value v1 = isZeroReg(*rt1) ? ignil::Value{ignil::Const{0, elemWidth}}
                                    : ignil::Value{*rt1};
  ignil::Value v2 = isZeroReg(*rt2) ? ignil::Value{ignil::Const{0, elemWidth}}
                                    : ignil::Value{*rt2};

  constexpr ignil::Width ptrWidth = 64;
  ignil::Temp storeAddr;
  ignil::Temp writebackAddr;

  if (isPost) {
    auto baseReg = toReg(mc.getOperand(baseIdx).getReg());
    if (!baseReg) {
      logger_.log("Error liftStorePair in addr {:#x} no base", addr);
      return;
    }
    storeAddr = newTemp(tmp, ptrWidth);
    out.append({ignil::Opcode::COPY, storeAddr, {*baseReg}, addr});
    writebackAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
  } else if (isPre) {
    storeAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
    writebackAddr = storeAddr;
  } else {
    storeAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
  }

  const auto elemBytes = static_cast<std::uint64_t>(elemWidth / 8);

  out.append({ignil::Opcode::STORE, std::nullopt, {storeAddr, v1}, addr});
  auto addr2 = newTemp(tmp, ptrWidth);
  out.append({ignil::Opcode::ADD,
              addr2,
              {storeAddr, ignil::Const{elemBytes, ptrWidth}},
              addr});
  out.append({ignil::Opcode::STORE, std::nullopt, {addr2, v2}, addr});

  if (isPrePost) {
    auto baseReg = toReg(mc.getOperand(baseIdx).getReg());
    if (baseReg)
      out.append({ignil::Opcode::COPY, *baseReg, {writebackAddr}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftAdr(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();

  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftAdr in addr {:#x} no dst", addr);
    return;
  }

  const auto imm = mc.getOperand(1).getImm();
  std::uint64_t value;
  if (opc == opADRP_) {
    // ADRP: Rd = (PC & ~0xFFF) + imm*0x1000. The base is the *page-aligned*
    // instruction address, not the raw address - critical and easy to miss,
    // since ADRP is almost never itself sitting on a 4K boundary.
    const std::uint64_t page = addr & ~std::uint64_t{0xFFF};
    value = page + static_cast<std::uint64_t>(imm) * 0x1000;
  } else {
    // ADR: Rd = PC + imm, byte-precise, no alignment.
    value = addr + static_cast<std::uint64_t>(imm);
  }

  if (isZeroReg(*dst))
    return;

  out.append(
          {ignil::Opcode::COPY, *dst, {ignil::Const{value, dst->width}}, addr});
}

dragon::ignil::Temp dragon::arm::ARMIGNILLifter::emitCondition(
        unsigned condCode, std::uint64_t addr, ignil::Block &out,
        std::uint32_t &tmp) const {
  // AArch64CC::CondCode enum (AArch64BaseInfo.h):
  //   0=EQ,1=NE,2=CS/HS,3=CC/LO,4=MI,5=PL,6=VS,7=VC,
  //   8=HI,9=LS,10=GE,11=LT,12=GT,13=LE,14=AL,15=NV
  auto flagSet = [&](ignil::Reg flag) -> ignil::Temp {
    auto t = newTemp(tmp, 8);
    out.append({ignil::Opcode::COPY, t, {flag}, addr});
    auto cond = newTemp(tmp, 1);
    out.append({ignil::Opcode::NEQ, cond, {t, ignil::Const{0, 8}}, addr});
    return cond;
  };
  auto flagClear = [&](ignil::Reg flag) -> ignil::Temp {
    auto t = newTemp(tmp, 8);
    out.append({ignil::Opcode::COPY, t, {flag}, addr});
    auto cond = newTemp(tmp, 1);
    out.append({ignil::Opcode::EQ, cond, {t, ignil::Const{0, 8}}, addr});
    return cond;
  };
  auto readFlag = [&](ignil::Reg flag) -> ignil::Temp {
    auto t = newTemp(tmp, 8);
    out.append({ignil::Opcode::COPY, t, {flag}, addr});
    return t;
  };

  switch (condCode) {
    case 0:
      return flagSet(regZF_); // EQ: Z=1
    case 1:
      return flagClear(regZF_); // NE: Z=0
    case 2:
      return flagSet(regCF_); // CS/HS: C=1
    case 3:
      return flagClear(regCF_); // CC/LO: C=0
    case 4:
      return flagSet(regNF_); // MI: N=1
    case 5:
      return flagClear(regNF_); // PL: N=0
    case 6:
      return flagSet(regVF_); // VS: V=1
    case 7:
      return flagClear(regVF_); // VC: V=0
    case 8: { // HI: C=1 AND Z=0
      auto c = flagSet(regCF_), zClr = flagClear(regZF_);
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::AND, cond, {c, zClr}, addr});
      return cond;
    }
    case 9: { // LS: C=0 OR Z=1
      auto cClr = flagClear(regCF_), z = flagSet(regZF_);
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::OR, cond, {cClr, z}, addr});
      return cond;
    }
    case 10: { // GE: N==V
      auto n = readFlag(regNF_), v = readFlag(regVF_);
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::EQ, cond, {n, v}, addr});
      return cond;
    }
    case 11: { // LT: N!=V
      auto n = readFlag(regNF_), v = readFlag(regVF_);
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::NEQ, cond, {n, v}, addr});
      return cond;
    }
    case 12: { // GT: Z=0 AND N==V
      auto zClr = flagClear(regZF_);
      auto n = readFlag(regNF_), v = readFlag(regVF_);
      auto nEqV = newTemp(tmp, 1);
      out.append({ignil::Opcode::EQ, nEqV, {n, v}, addr});
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::AND, cond, {zClr, nEqV}, addr});
      return cond;
    }
    case 13: { // LE: Z=1 OR N!=V
      auto z = flagSet(regZF_);
      auto n = readFlag(regNF_), v = readFlag(regVF_);
      auto nNeV = newTemp(tmp, 1);
      out.append({ignil::Opcode::NEQ, nNeV, {n, v}, addr});
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::OR, cond, {z, nNeV}, addr});
      return cond;
    }
    case 14:
    case 15: { // AL, NV - always taken (NV is reserved, treated as AL)
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::COPY, cond, {ignil::Const{1, 1}}, addr});
      return cond;
    }
    default: {
      auto undef = newTemp(tmp, 1);
      out.append({ignil::Opcode::UNDEF, undef, {}, addr});
      return undef;
    }
  }
}

void dragon::arm::ARMIGNILLifter::liftBcc(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  // op[0]=condition code (imm), op[1]=target (imm, instruction-count units,
  // relative to this instruction's own address - not addr+size, and not
  // byte-scaled). Verified via llvm-mc -disassemble -show-inst.
  const auto condCode = static_cast<unsigned>(mc.getOperand(0).getImm());
  const auto offsetUnits = mc.getOperand(1).getImm();
  const auto taken = static_cast<std::uint64_t>(
          static_cast<std::int64_t>(addr) + offsetUnits * 4);
  const std::uint64_t fallthrough = addr + 4; // AArch64 insns are fixed 4B

  auto cond = emitCondition(condCode, addr, out, tmp);
  out.append({ignil::Opcode::CJMP,
              std::nullopt,
              {cond, ignil::Const{taken, 64}, ignil::Const{fallthrough, 64}},
              addr});
}

void dragon::arm::ARMIGNILLifter::liftCbz(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();
  const bool isNonZero = (opc == opCBNZW_ || opc == opCBNZX_);
  const ignil::Width width = (opc == opCBZW_ || opc == opCBNZW_) ? 32 : 64;

  // op[0]=Rt, op[1]=target (same instruction-count/own-address convention as
  // Bcc above).
  auto rt = toReg(mc.getOperand(0).getReg());
  const auto offsetUnits = mc.getOperand(1).getImm();
  const auto taken = static_cast<std::uint64_t>(
          static_cast<std::int64_t>(addr) + offsetUnits * 4);
  const std::uint64_t fallthrough = addr + 4;

  ignil::Value val = (!rt || isZeroReg(*rt))
                             ? ignil::Value{ignil::Const{0, width}}
                             : ignil::Value{*rt};
  auto cond = newTemp(tmp, 1);
  out.append({isNonZero ? ignil::Opcode::NEQ : ignil::Opcode::EQ,
              cond,
              {val, ignil::Const{0, width}},
              addr});
  out.append({ignil::Opcode::CJMP,
              std::nullopt,
              {cond, ignil::Const{taken, 64}, ignil::Const{fallthrough, 64}},
              addr});
}

void dragon::arm::ARMIGNILLifter::liftTbz(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();
  const bool isNonZero = (opc == opTBNZW_ || opc == opTBNZX_);
  const ignil::Width width = (opc == opTBZW_ || opc == opTBNZW_) ? 32 : 64;

  // op[0]=Rt, op[1]=bit number, op[2]=target (same convention as Bcc/CBZ).
  auto rt = toReg(mc.getOperand(0).getReg());
  const auto bitNum = static_cast<std::uint64_t>(mc.getOperand(1).getImm());
  const auto offsetUnits = mc.getOperand(2).getImm();
  const auto taken = static_cast<std::uint64_t>(
          static_cast<std::int64_t>(addr) + offsetUnits * 4);
  const std::uint64_t fallthrough = addr + 4;

  ignil::Value val = (!rt || isZeroReg(*rt))
                             ? ignil::Value{ignil::Const{0, width}}
                             : ignil::Value{*rt};
  auto masked = newTemp(tmp, width);
  out.append({ignil::Opcode::AND,
              masked,
              {val, ignil::Const{std::uint64_t{1} << bitNum, width}},
              addr});
  auto cond = newTemp(tmp, 1);
  out.append({isNonZero ? ignil::Opcode::NEQ : ignil::Opcode::EQ,
              cond,
              {masked, ignil::Const{0, width}},
              addr});
  out.append({ignil::Opcode::CJMP,
              std::nullopt,
              {cond, ignil::Const{taken, 64}, ignil::Const{fallthrough, 64}},
              addr});
}

void dragon::arm::ARMIGNILLifter::liftBranch(const llvm::MCInst &mc,
                                             std::uint64_t addr,
                                             ignil::Block &out,
                                             std::uint32_t &tmp) const {
  // B: single imm operand (instruction-count units, own-address relative).
  // BR: single register operand (indirect).
  const auto &op = mc.getOperand(0);
  if (op.isImm()) {
    const auto target = static_cast<std::uint64_t>(
            static_cast<std::int64_t>(addr) + op.getImm() * 4);
    out.append({ignil::Opcode::JMP,
                std::nullopt,
                {ignil::Const{target, 64}},
                addr});
  } else if (op.isReg()) {
    auto targetReg = toReg(op.getReg());
    if (!targetReg) {
      logger_.log("Error liftBranch in addr {:#x} no target register", addr);
      return;
    }
    out.append({ignil::Opcode::JMP, std::nullopt, {*targetReg}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftCall(const llvm::MCInst &mc,
                                           std::uint64_t addr,
                                           ignil::Block &out,
                                           std::uint32_t &tmp) const {
  // BL: single imm operand (instruction-count units, own-address relative).
  // BLR: single register operand (indirect).
  const auto &op = mc.getOperand(0);
  if (op.isImm()) {
    const auto target = static_cast<std::uint64_t>(
            static_cast<std::int64_t>(addr) + op.getImm() * 4);
    out.append({ignil::Opcode::CALL,
                std::nullopt,
                {ignil::Const{target, 64}},
                addr});
  } else if (op.isReg()) {
    auto targetReg = toReg(op.getReg());
    if (!targetReg) {
      logger_.log("Error liftCall in addr {:#x} no target register", addr);
      return;
    }
    out.append({ignil::Opcode::CALL, std::nullopt, {*targetReg}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftRet(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  ignil::Op ret{ignil::Opcode::RET,std::nullopt,{},addr};
  const auto name=instrInfo_->getName(mc.getOpcode());
  // Keep the operand-free IGNIL abstraction. Ordinary A64 RET records its
  // actual register: aux 0 is legacy LR, aux 1..32 means X0..X31 (XZR).
  if (name=="RET" || name=="RET_ReallyLR") {
    ret.aux=31;
    if (mc.getNumOperands() && mc.getOperand(0).isReg())
      if (auto reg=toReg(mc.getOperand(0).getReg());reg && reg->width==64 && reg->offset<=248 && reg->offset%8==0)
        ret.aux=reg->offset/8+1;
  }
  out.append(std::move(ret));
}
